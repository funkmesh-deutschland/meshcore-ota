#ifndef MCOTA_LAYOUT_H
#define MCOTA_LAYOUT_H

#define MCOTA_FLASH_PAGE 0x1000u

#if defined(MCOTA_LAYOUT_S140_V7)
#define MCOTA_LOADER_ADDR 0x27000u
#elif defined(MCOTA_LAYOUT_S140_V6)
#define MCOTA_LOADER_ADDR 0x26000u
#else
#error "memory layout not selected"
#endif

#define MCOTA_APP_END 0xED000u
#ifndef MCOTA_STATUS_PAGES
#define MCOTA_STATUS_PAGES 2u
#endif
#define MCOTA_EXT_FLAG 0x80000000u
#define MCOTA_KEYS_ADDR (MCOTA_APP_END - MCOTA_FLASH_PAGE)
#define MCOTA_STATUS_ADDR (MCOTA_KEYS_ADDR - MCOTA_STATUS_PAGES * MCOTA_FLASH_PAGE)

#if defined(MCOTA_BOARD_XIAO_NRF52)
#define MCOTA_EXT_SIZE 0x200000u
#define MCOTA_EXT_PIN_SCK 21u
#define MCOTA_EXT_PIN_CS 25u
#define MCOTA_EXT_PIN_IO0 20u
#define MCOTA_EXT_PIN_IO1 24u
#define MCOTA_EXT_PIN_IO2 22u
#define MCOTA_EXT_PIN_IO3 23u
#endif

#ifdef MCOTA_EXT_SIZE
#define MCOTA_LOADER_PAGES 1u
#define MCOTA_SLOT_A_ADDR (MCOTA_LOADER_ADDR + MCOTA_LOADER_PAGES * MCOTA_FLASH_PAGE)
#define MCOTA_SLOT_PAGES ((MCOTA_STATUS_ADDR - MCOTA_SLOT_A_ADDR) / MCOTA_FLASH_PAGE)
#define MCOTA_SLOT_B_ADDR MCOTA_EXT_FLAG
#define MCOTA_SCRATCH_ADDR (MCOTA_EXT_FLAG + MCOTA_SLOT_PAGES * MCOTA_FLASH_PAGE)
#define MCOTA_STORE_ADDR (MCOTA_SCRATCH_ADDR + MCOTA_FLASH_PAGE)
#define MCOTA_STORE_SIZE (MCOTA_EXT_SIZE - (MCOTA_STORE_ADDR - MCOTA_EXT_FLAG))
#else
#define MCOTA_COMPACT 1
#define MCOTA_LOADER_PAGES 3u
#define MCOTA_SLOT_A_ADDR (MCOTA_LOADER_ADDR + MCOTA_LOADER_PAGES * MCOTA_FLASH_PAGE)
#define MCOTA_SLOT_PAGES ((MCOTA_STATUS_ADDR - MCOTA_SLOT_A_ADDR) / MCOTA_FLASH_PAGE)
#define MCOTA_POOL_END MCOTA_STATUS_ADDR
#endif

#define MCOTA_WRITE_MIN MCOTA_SLOT_A_ADDR
#define MCOTA_WRITE_MAX (MCOTA_STATUS_ADDR + MCOTA_STATUS_PAGES * MCOTA_FLASH_PAGE)

#endif
